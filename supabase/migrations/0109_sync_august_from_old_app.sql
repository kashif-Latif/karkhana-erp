--   Advances: both systems already hold the same eight rows totalling
--   Rs 111,815, verified against the old app before writing this. Nothing to do.
--   Days after the 29th: the old app has none, so any 30th or 31st marked here
--   stays exactly as it is.
--
-- Safe to run more than once — same rows, same result.

